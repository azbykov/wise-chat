import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { type HydratedDocument, Types } from 'mongoose';

@Schema({ collection: 'messages', timestamps: { createdAt: true, updatedAt: false } })
export class Message {
  _id: Types.ObjectId;

  @Prop({ type: Types.ObjectId, required: true })
  conversationId: Types.ObjectId;

  /** 1, 2, 3… within the conversation, without gaps: the order, the cursor and the catch-up. */
  @Prop({ required: true })
  seq: number;

  @Prop({ type: Types.ObjectId, required: true })
  senderId: Types.ObjectId;

  @Prop({ required: true })
  text: string;

  /** Generated by the client; a retry with the same id returns the stored message. */
  @Prop({ required: true })
  clientMessageId: string;

  createdAt: Date;
}

export type MessageDocument = HydratedDocument<Message>;
export const MessageSchema = SchemaFactory.createForClass(Message);
MessageSchema.index({ conversationId: 1, seq: 1 }, { unique: true });
MessageSchema.index({ senderId: 1, clientMessageId: 1 }, { unique: true });
