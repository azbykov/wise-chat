import { Transform, Type } from 'class-transformer';
import { IsInt, IsOptional, IsString, IsUUID, Length, Matches, Max, Min } from 'class-validator';

export const MESSAGE_MAX_LENGTH = 2000;
export const MESSAGES_PAGE_DEFAULT = 30;
export const MESSAGES_PAGE_MAX = 100;

const trim = ({ value }: { value: unknown }) => (typeof value === 'string' ? value.trim() : value);

export class SendMessageDto {
  /** Trimmed; line breaks and tabs are fine, other control characters are not. */
  @Transform(trim)
  @IsString()
  @Length(1, MESSAGE_MAX_LENGTH, {
    message: `Message must be 1 to ${MESSAGE_MAX_LENGTH} characters long`,
  })
  @Matches(/^(?:[^\p{Cc}]|[\n\t])*$/u, { message: 'Message cannot contain control characters' })
  text: string;

  /** Generated by the client for each new message and kept for its retries. */
  @IsUUID('all', { message: 'clientMessageId must be a UUID' })
  clientMessageId: string;
}

export class ListMessagesQuery {
  /** Messages with a smaller seq: the page before the oldest one loaded. */
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  before?: number;

  /** Messages with a larger seq: whatever arrived after the newest one loaded. */
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(0)
  after?: number;

  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(MESSAGES_PAGE_MAX)
  limit: number = MESSAGES_PAGE_DEFAULT;
}

export class MarkReadDto {
  /** The newest message the user has seen; larger values are capped at the newest message. */
  @Type(() => Number)
  @IsInt()
  @Min(0)
  seq: number;
}
